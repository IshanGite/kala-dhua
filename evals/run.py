"""Runs the eval suites one after another (they share the local model server) and writes docs/EVALS.md from the result files.
Usage: python -m evals.run [--suite name ...] [--report-only]"""
from __future__ import annotations

import argparse
import asyncio
import inspect
import json
import platform
import subprocess
import sys
import time
import traceback

from evals.common import OUT, REPO, models, save

ORDER = ["utility", "intent", "actions", "tasks", "memory", "digest", "forgetting", "security", "reliability", "multimodal"]
TITLES = {"utility": "Exact answers by code", "intent": "Understanding what was asked", "actions": "Reading action requests into slots", "tasks": "Doing the task end to end",
          "memory": "Grounded answers from memory", "digest": "Digest grouping and flags", "forgetting": "Forgetting over 180 simulated days", "security": "Prompt-injection red team",
          "reliability": "Reliability and graceful degradation", "multimodal": "Pictures and speech"}


def fmt(v: object) -> str:
    if isinstance(v, dict) and {"k", "n"} <= v.keys():
        lo, hi = v.get("ci95", [None, None])
        return f"{v['rate'] * 100:.1f}% ({v['k']}/{v['n']}), 95% CI {lo * 100:.0f}–{hi * 100:.0f}%" if v.get("rate") is not None else f"0/{v['n']}"
    if isinstance(v, dict) and "p50_ms" in v:
        return f"p50 {v['p50_ms']:.0f} ms, p95 {v['p95_ms']:.0f} ms (n={v['n']})"
    if isinstance(v, dict):
        return "; ".join(f"{k}: {fmt(x)}" for k, x in v.items())
    return str(v)


def run_suites(names: list[str]) -> None:
    import importlib
    for name in names:
        t = time.time()
        print(f"== {name}", flush=True)
        try:
            m = importlib.import_module(f"evals.s_{name}")
            r = m.run()
            if inspect.isawaitable(r):
                r = asyncio.run(r)
            r["seconds"] = round(time.time() - t, 1)
            save(r)
            print(f"   done in {r['seconds']}s", flush=True)
        except Exception:  # noqa: BLE001
            traceback.print_exc()
            save({"suite": name, "error": traceback.format_exc()[-800:], "metrics": {}})


def machine() -> str:
    try:
        chip = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True).stdout.strip()  # noqa: S603, S607
    except Exception:  # noqa: BLE001
        chip = platform.processor()
    return f"{chip or platform.machine()}, {platform.system()} {platform.release()}, Python {platform.python_version()}"


def report() -> str:
    L = ["# Ragnarok evaluation report", "", "Generated by `python -m evals.run`. Every number below was measured on this machine by the harness in `evals/`; raw results are in `docs/evidence/evals/*.json`.", "",
         f"- Machine: {machine()}", f"- Models (all local, via Ollama unless noted): {json.dumps(models())}", "- No cloud service is used at any point; the model server is on loopback.",
         "- Datasets are written by the author of the system. Where a suite was tuned on its own data the suite says so; held-out sets are reported separately. Confidence intervals are Wilson 95%. Small samples mean wide intervals; read the interval, not the point value.", ""]
    for name in ORDER:
        f = OUT / f"{name}.json"
        if not f.exists():
            continue
        r = json.loads(f.read_text(encoding="utf-8"))
        L += [f"## {TITLES.get(name, name)}", ""]
        if r.get("requirement"):
            L += [f"Requirement: {r['requirement']}  ", f"Samples: {r.get('n', '?')}" + (f"  ·  run time {r['seconds']} s" if r.get("seconds") else ""), ""]
        if r.get("error"):
            L += ["**The suite crashed**: `" + r["error"].replace("\n", " ")[-300:] + "`", ""]
            continue
        L += ["| Metric | Result |", "|---|---|"]
        for k, v in (r.get("metrics") or {}).items():
            L.append(f"| {k.replace('_', ' ')} | {fmt(v)} |")
        L.append("")
        fails = r.get("failures") or []
        if fails:
            L += [f"Misses ({len(fails)}), shown so the numbers can be checked:", ""]
            for x in fails[:12]:
                L.append("- " + (json.dumps(x, ensure_ascii=False)[:220] if not isinstance(x, str) else x[:220]))
            L.append("")
        if r.get("notes"):
            L += [f"_Note: {r['notes']}_", ""]
    ev = REPO / "docs" / "evidence"
    L += ["## Other measurements (separate scripts)", ""]
    def j(n: str):  # noqa: ANN202
        p = ev / n
        return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None
    if (d := j("nfr2_1.json")):
        L.append(f"- Retrieval over {d['corpus_messages']} messages: p50 {d['retrieval_ms']['p50']} ms, p95 {d['retrieval_ms']['p95']} ms, recall@5 {d['recall_at_5']} (`scripts/bench_nfr2_1.py`).")
    if (d := j("nfr2_2_load.json")):
        s = d["summary"]
        L.append(f"- Resource use under load: agent plus models {s['agent_plus_models_machine_share_pct']['mean']}% mean, {s['agent_plus_models_machine_share_pct']['max']}% max of the machine (gate {s['gate_pct']}%), app memory up to {s['rss_mb_max']} MB (`scripts/bench_nfr2_2.py`).")
    if (d := j("nfr3_2_restart.json")):
        L.append(f"- Crash recovery: kill -9 while a task waits for approval, back with the state restored in {d['process_start_to_state_restored_s']} s (gate {d['gate_s']} s), task asks again: {d['interrupted_task_resumed_and_asking_again']} (`scripts/bench_restart.py`).")
    if (d := j("scrolls.json")):
        L.append(f"- Skill scrolls: routing {d['routing']['correct']}/{d['routing']['n']} on the set it was tuned on, {d['routing_holdout']['correct']}/{d['routing_holdout']['n']} on a held-out set (`scripts/eval_scrolls.py`).")
    if (d := j("ingest_latency.json")):
        L.append(f"- Gmail arrival to searchable memory: {d['gmail_arrival_to_memory_s']} s, including Gmail's own delay and an {d['poll_interval_gmail_s']} s poll.")
    L.append("")
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite", nargs="*", default=None)
    ap.add_argument("--report-only", action="store_true")
    a = ap.parse_args()
    if not a.report_only:
        run_suites(a.suite or ORDER)
    (REPO / "docs" / "EVALS.md").write_text(report(), encoding="utf-8")
    print("wrote docs/EVALS.md")


if __name__ == "__main__":
    sys.path.insert(0, str(REPO))
    main()
